import { test,expect } from '@playwright/test';
test.describe.configure({mode:'serial',timeout:180000});
test('clean browser registration, real signed delivery, rejection and deduplication',async({page})=>{
 const suffix=Date.now().toString(36);
 await page.goto('/');
 await page.getByRole('button',{name:'Create an account',exact:true}).click();
 await page.getByLabel('Your name').fill('Release Reviewer '+suffix);
 await page.getByLabel('Email address').fill('reviewer-'+suffix+'@example.local');
 await page.getByLabel('Password',{exact:true}).fill('synthetic-release-password-123');
 await page.getByLabel('Confirm password').fill('synthetic-release-password-123');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Every connection. Under control.'})).toBeVisible();
 await page.getByRole('link',{name:'Simulation Lab',exact:false}).click();
 await page.locator('.scenario-card').filter({hasText:'The golden path'}).getByRole('button',{name:'Run scenario'}).click();
 await expect(page.locator('tbody tr').filter({hasText:'The golden path'})).toContainText('Verified outcome',{timeout:60000});
 await page.locator('.scenario-card').filter({hasText:'Reject a forged event'}).getByRole('button',{name:'Run scenario'}).click();
 await expect(page.locator('tbody tr').filter({hasText:'Reject a forged event'})).toContainText('Verified outcome',{timeout:30000});
 await page.locator('.scenario-card').filter({hasText:'Keep duplicates harmless'}).getByRole('button',{name:'Run scenario'}).click();
 await expect(page.locator('tbody tr').filter({hasText:'Keep duplicates harmless'})).toContainText('Verified outcome',{timeout:30000});
 await page.locator('.scenario-card').filter({hasText:'Recover from an outage'}).getByRole('button',{name:'Run scenario'}).click();
 await expect(page.locator('tbody tr').filter({hasText:'Recover from an outage'})).toContainText('Verified outcome',{timeout:60000});
 await page.getByLabel('Simulation provider').selectOption('github');
 await page.locator('.scenario-card').filter({hasText:'The golden path'}).getByRole('button',{name:'Run scenario'}).click();
 await expect(page.locator('tbody tr').filter({hasText:'The golden path'}).first()).toContainText('Verified outcome',{timeout:60000});
 await page.getByRole('link',{name:'Monitor',exact:true}).click();
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export deliveries',exact:true}).click();
 expect((await download).suggestedFilename()).toBe('apiqendra-deliveries.csv');
});
test('persistent outage can be recovered and deliberately replayed',async({page})=>{
 const suffix=Date.now().toString(36);
 await page.goto('/');
 await page.getByRole('button',{name:'Create an account',exact:true}).click();
 await page.getByLabel('Your name').fill('Recovery Reviewer');
 await page.getByLabel('Email address').fill('recovery-'+suffix+'@example.local');
 await page.getByLabel('Password',{exact:true}).fill('synthetic-release-password-123');
 await page.getByLabel('Confirm password').fill('synthetic-release-password-123');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await page.getByRole('link',{name:'Simulation Lab',exact:false}).click();
 const row=page.locator('tbody tr').filter({hasText:'Dead letter & replay'});
 await page.locator('.scenario-card').filter({hasText:'Dead letter & replay'}).getByRole('button',{name:'Run scenario'}).click();
 await expect(row).toContainText('Verified outcome',{timeout:90000});
 await row.getByRole('button',{name:'Recover destination'}).click();
 await row.locator('.delivery-chip').click();
 await page.getByRole('button',{name:'Replay delivery',exact:true}).click();
 await expect(page.getByRole('dialog').locator('.detail-banner')).toContainText('delivered',{timeout:60000});
});
